// Everything ink, from KanjiVG stroke data: node scripts/make-icons.mjs  (needs playwright-core and a Chromium)
//   1. src/ink/glyph.js         言 as brush outlines, for the React ink components (sign-in, welcome)
//   2. public/ink/*.png         the simulated ink-in-paper fields for the opening animation (scripts/ink-field.mjs)
//   3. public/icon-*.png, apple-touch-icon.png
//                               the icon, rendered by the opening animation's own shader (src/splash/renderer.js)
//                               at the moment the animation hands over to the app, so the two always match
// The brush outlines: each KanjiVG centre line becomes a filled outline whose width follows the pen
// (firm start, full body, lifting end).
import { chromium } from "playwright-core";
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const GLYPH = "言";
const chars = [...fs.readFileSync("public/strokes/index.txt", "utf8")];
const centre = JSON.parse(fs.readFileSync(`public/strokes/${Math.floor(chars.indexOf(GLYPH) / 96)}.json`, "utf8"))[GLYPH];
const exe = ["/opt/pw-browsers/chromium-1194/chrome-linux/chrome", "/opt/pw-browsers/chromium"].find((p) => { try { return fs.statSync(p).isFile(); } catch { return false; } });

const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const p = await b.newPage();

// ---- 1. outlines
await p.setContent(`<svg xmlns="http://www.w3.org/2000/svg" id="s"></svg>`);
const outlines = await p.evaluate((paths) => {
  const NS = "http://www.w3.org/2000/svg";
  const svg = document.getElementById("s");
  const f = (n) => (Math.round(n * 10) / 10).toString();
  return paths.map((d, si) => {
    const el = document.createElementNS(NS, "path"); el.setAttribute("d", d); svg.appendChild(el);
    const L = el.getTotalLength();
    const N = Math.max(14, Math.ceil(L / 2.2));
    const pts = Array.from({ length: N + 1 }, (_, i) => el.getPointAtLength((L * i) / N));
    const W = 7.4;
    const left = [], right = [];
    for (let i = 0; i <= N; i++) {
      const a = pts[Math.max(0, i - 1)], c = pts[Math.min(N, i + 1)];
      let tx = c.x - a.x, ty = c.y - a.y; const m = Math.hypot(tx, ty) || 1; tx /= m; ty /= m;
      const t = i / N;
      // pen pressure: lands firmly, full body, lifts at the end (longer strokes lift more)
      const land = 0.78 + 0.22 * Math.min(1, t / 0.07);
      const lift = 1 - (L > 24 ? 0.62 : 0.4) * Math.pow(Math.max(0, (t - 0.72) / 0.28), 1.6);
      const body = 1 + 0.07 * Math.sin(t * Math.PI);
      const w = (W * land * lift * body) / 2;
      left.push([pts[i].x - ty * w, pts[i].y + tx * w]);
      right.push([pts[i].x + ty * w, pts[i].y - tx * w]);
    }
    const ring = [...left, ...right.reverse()];
    el.remove();
    return "M" + ring.map(([x, y]) => `${f(x)} ${f(y)}`).join("L") + "Z";
  });
}, centre);
const lengths = await p.evaluate((paths) => paths.map((d) => { const el = document.createElementNS("http://www.w3.org/2000/svg", "path"); el.setAttribute("d", d); return el.getTotalLength(); }), centre);
fs.mkdirSync("src/ink", { recursive: true });
fs.writeFileSync("src/ink/glyph.js", `// Generated by scripts/make-icons.mjs from KanjiVG (© Ulrich Apel, CC BY-SA 3.0). Do not edit.\n// 言 as brush outlines (fill) and centre lines (to reveal them), in a 109 x 109 box.\nexport const INK_GLYPH = ${JSON.stringify({ char: GLYPH, size: 109, outline: outlines, centre, lengths: lengths.map((l) => Math.round(l * 10) / 10) })};\n`);

// ---- 2. the ink fields
execFileSync(process.execPath, ["scripts/ink-field.mjs"], { stdio: "inherit" });

// ---- 3. the icons: the last frame of the opening animation
const K = JSON.parse(fs.readFileSync("src/splash/constants.json", "utf8"));
const renderer = fs.readFileSync("src/splash/renderer.js", "utf8");
// ink time when the opening hands over to the app: inkTime(MIN_MS = 1.2 s, slow 0.3, knee 0.6) in src/splash/splash.js
const ICON_SIM = 0.3 * 1.2 + 0.7 * 0.6 * Math.tanh(1.2 / 0.6);
const ORIGIN = "http://kotoba.icons";
await p.route(`${ORIGIN}/**`, (r) => {
  const url = r.request().url();
  if (url.endsWith(".png")) return r.fulfill({ contentType: "image/png", body: fs.readFileSync("public/ink/" + url.split("/").pop()) });
  return r.fulfill({ contentType: "text/html", body: `<body style="margin:0"><canvas id="c"></canvas><script>${renderer}\nkotobaInk(window);</script></body>` });
});
await p.goto(`${ORIGIN}/`);
for (const [name, size, fill] of [["icon-192", 192, 1], ["icon-512", 512, 1], ["icon-maskable-512", 512, 0.8], ["apple-touch-icon", 180, 1]]) {
  // render at 3× and let the browser scale down, for smooth edges
  const S = size * 3;
  const data = await p.evaluate(async ({ K, S, size, fill, sim }) => {
    const bmp = async (u) => createImageBitmap(await (await fetch(u)).blob(), { premultiplyAlpha: "none", colorSpaceConversion: "none" });
    const c = document.getElementById("c"); c.width = S; c.height = S;
    const gl = c.getContext("webgl", { preserveDrawingBuffer: true });
    const r = KotobaInk.create(gl, await bmp("/ink/field.png"), await bmp("/ink/flood.png"), K);
    r.draw({ w: S, h: S, box: [S / 2, S / 2, S * fill], scale: (3 * size) / 300, sim, time: 3, exit: -1, paper: [0.925, 0.89, 0.816], bg: [0, 0, 0] });
    const out = document.createElement("canvas"); out.width = size; out.height = size;
    const ctx = out.getContext("2d"); ctx.imageSmoothingQuality = "high"; ctx.drawImage(c, 0, 0, size, size);
    return out.toDataURL("image/png");
  }, { K, S, size, fill, sim: ICON_SIM });
  fs.writeFileSync(`public/${name}.png`, Buffer.from(data.split(",")[1], "base64"));
}
try { fs.unlinkSync("public/icon.svg"); } catch { /* already gone */ }
await b.close();
console.log("glyph outlines, ink fields and icons written");
