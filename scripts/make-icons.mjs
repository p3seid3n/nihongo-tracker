// Draws the app icon and the opening animation's artwork from KanjiVG stroke data: node scripts/make-icons.mjs
// Needs playwright-core and a Chromium. Writes
//   public/icon-*.png, apple-touch-icon.png, icon.svg   the icon: black brush 言 on washi paper, red sun
//   src/ink/glyph.js                                    the brush outlines, for the React ink components
//   index.html (between the splash markers)            the inline opening animation
// The brush: KanjiVG gives each stroke as a centre line. Each stroke becomes a filled outline whose width follows
// the pen (firm start, full body, lifting end), and is revealed by a mask that draws the centre line.
import { chromium } from "playwright-core";
import fs from "node:fs";

const GLYPH = "言";
const chars = [...fs.readFileSync("public/strokes/index.txt", "utf8")];
const centre = JSON.parse(fs.readFileSync(`public/strokes/${Math.floor(chars.indexOf(GLYPH) / 96)}.json`, "utf8"))[GLYPH];
const exe = ["/opt/pw-browsers/chromium-1194/chrome-linux/chrome", "/opt/pw-browsers/chromium"].find((p) => { try { return fs.statSync(p).isFile(); } catch { return false; } });

const PAPER = "#ece3d0", INK = "#16120f", SUN = "#c93a2b";

const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const p = await b.newPage();

// ---- 1. outlines
await p.setContent(`<svg xmlns="http://www.w3.org/2000/svg" id="s"></svg>`);
const outlines = await p.evaluate((paths) => {
  const NS = "http://www.w3.org/2000/svg";
  const svg = document.getElementById("s");
  const f = (n) => (Math.round(n * 10) / 10).toString();
  return paths.map((d, si) => {
    const el = document.createElementNS(NS, "path"); el.setAttribute("d", d); svg.appendChild(el);
    const L = el.getTotalLength();
    const N = Math.max(14, Math.ceil(L / 2.2));
    const pts = Array.from({ length: N + 1 }, (_, i) => el.getPointAtLength((L * i) / N));
    const W = 7.4;
    const left = [], right = [];
    for (let i = 0; i <= N; i++) {
      const a = pts[Math.max(0, i - 1)], c = pts[Math.min(N, i + 1)];
      let tx = c.x - a.x, ty = c.y - a.y; const m = Math.hypot(tx, ty) || 1; tx /= m; ty /= m;
      const t = i / N;
      // pen pressure: lands firmly, full body, lifts at the end (longer strokes lift more)
      const land = 0.78 + 0.22 * Math.min(1, t / 0.07);
      const lift = 1 - (L > 24 ? 0.62 : 0.4) * Math.pow(Math.max(0, (t - 0.72) / 0.28), 1.6);
      const body = 1 + 0.07 * Math.sin(t * Math.PI);
      const w = (W * land * lift * body) / 2;
      left.push([pts[i].x - ty * w, pts[i].y + tx * w]);
      right.push([pts[i].x + ty * w, pts[i].y - tx * w]);
    }
    const ring = [...left, ...right.reverse()];
    el.remove();
    return "M" + ring.map(([x, y]) => `${f(x)} ${f(y)}`).join("L") + "Z";
  });
}, centre);
const lengths = await p.evaluate((paths) => paths.map((d) => { const el = document.createElementNS("http://www.w3.org/2000/svg", "path"); el.setAttribute("d", d); return el.getTotalLength(); }), centre);
fs.mkdirSync("src/ink", { recursive: true });
fs.writeFileSync("src/ink/glyph.js", `// Generated by scripts/make-icons.mjs from KanjiVG (© Ulrich Apel, CC BY-SA 3.0). Do not edit.\n// 言 as brush outlines (fill) and centre lines (to reveal them), in a 109 x 109 box.\nexport const INK_GLYPH = ${JSON.stringify({ char: GLYPH, size: 109, outline: outlines, centre, lengths: lengths.map((l) => Math.round(l * 10) / 10) })};\n`);

// ---- 2. the scene, shared by icons and splash
const defs = (id) => `<filter id="${id}-ink" x="-8%" y="-8%" width="116%" height="116%" color-interpolation-filters="sRGB">
<feTurbulence type="fractalNoise" baseFrequency="0.09" numOctaves="3" seed="7" result="n"/>
<feDisplacementMap in="SourceGraphic" in2="n" scale="3.2" xChannelSelector="R" yChannelSelector="G" result="d"/>
<feGaussianBlur in="d" stdDeviation="0.7" result="b"/>
<feComponentTransfer in="b"><feFuncA type="table" tableValues="0 0 0.15 0.85 1 1"/></feComponentTransfer></filter>
<filter id="${id}-paper" x="0" y="0" width="100%" height="100%"><feTurbulence type="fractalNoise" baseFrequency="0.8 0.35" numOctaves="3" seed="2" result="n"/>
<feColorMatrix in="n" type="matrix" values="0 0 0 0 0.35  0 0 0 0 0.28  0 0 0 0 0.18  0 0 0 0.55 -0.12"/></filter>
<radialGradient id="${id}-vig" cx="50%" cy="46%" r="78%"><stop offset=".55" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#3a2c18" stop-opacity=".30"/></radialGradient>
<filter id="${id}-sunf" x="-10%" y="-10%" width="120%" height="120%"><feTurbulence type="fractalNoise" baseFrequency="0.05" numOctaves="2" seed="4" result="n"/><feDisplacementMap in="SourceGraphic" in2="n" scale="5" xChannelSelector="R" yChannelSelector="G"/><feGaussianBlur stdDeviation="0.6"/></filter>`;

const scene = (size, pad, { rounded = false } = {}) => {
  const inner = size * (1 - pad * 2);
  const k = inner / 109;
  const ox = size * pad, oy = size * pad + size * 0.012;
  const r = rounded ? size * 0.22 : 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><defs>${defs("i")}<clipPath id="i-clip"><rect width="${size}" height="${size}" rx="${r}"/></clipPath></defs>
<g clip-path="url(#i-clip)"><rect width="${size}" height="${size}" fill="${PAPER}"/><rect width="${size}" height="${size}" filter="url(#i-paper)" opacity=".5"/><rect width="${size}" height="${size}" fill="url(#i-vig)"/>
<circle cx="${size * 0.665}" cy="${size * 0.335}" r="${size * 0.205}" fill="${SUN}" filter="url(#i-sunf)"/>
<g transform="translate(${ox} ${oy}) scale(${k})" fill="${INK}" filter="url(#i-ink)">${outlines.map((d) => `<path d="${d}"/>`).join("")}</g></g></svg>`;
};

const shoot = async (name, size, pad, opts) => {
  await p.setViewportSize({ width: size, height: size });
  await p.setContent(`<body style="margin:0;background:transparent">${scene(size, pad, opts)}</body>`);
  await p.screenshot({ path: `public/${name}.png`, omitBackground: true });
};
await shoot("icon-192", 192, 0.13);
await shoot("icon-512", 512, 0.13);
await shoot("icon-maskable-512", 512, 0.2);      // the glyph stays inside the 80 % safe circle
await shoot("apple-touch-icon", 180, 0.13);
fs.writeFileSync("public/icon.svg", scene(512, 0.13, { rounded: true }));

// ---- 3. the opening animation, inline in index.html
// Time runs fast and then slows: each stroke is drawn a little more slowly than the one before.
const n = outlines.length;
const STROKE_MS = [70, 85, 100, 125, 150, 190, 240].slice(0, n);
while (STROKE_MS.length < n) STROKE_MS.push(260);
let at = 140; const timing = STROKE_MS.map((ms) => { const t = { delay: at, ms }; at += Math.round(ms * 0.82); return t; });
const strokesEnd = timing[n - 1].delay + timing[n - 1].ms;
const css = `
#splash{position:fixed;inset:0;z-index:2147483000;display:flex;align-items:center;justify-content:center;background:var(--sp-bg,#151413);transition:opacity .45s cubic-bezier(.2,.7,.2,1),visibility 0s .45s}
#splash.out{opacity:0;visibility:hidden;pointer-events:none}
#splash .sp-tile{width:min(58vw,260px);aspect-ratio:1;position:relative;filter:drop-shadow(0 18px 40px rgba(0,0,0,.35));animation:sp-in .5s cubic-bezier(.05,.9,.1,1) both}
#splash svg{display:block;width:100%;height:100%;overflow:visible}
#splash .sp-m{fill:none;stroke:#fff;stroke-width:26;stroke-linecap:round;stroke-linejoin:round;stroke-dasharray:var(--len);stroke-dashoffset:var(--len);animation:sp-draw var(--ms) cubic-bezier(.05,.9,.1,1) var(--d) forwards}
#splash .sp-sun{transform-box:fill-box;transform-origin:50% 50%;transform:scale(.0);animation:sp-sun 1.5s cubic-bezier(.05,.9,.1,1) ${Math.round(strokesEnd * 0.55)}ms forwards}
#splash .sp-glyph{transform-origin:50% 55%;animation:sp-drift 2.6s cubic-bezier(.1,.8,.2,1) ${Math.round(strokesEnd * 0.6)}ms both}
@keyframes sp-in{from{opacity:0;transform:scale(.9)}to{opacity:1;transform:none}}
@keyframes sp-draw{to{stroke-dashoffset:0}}
@keyframes sp-sun{0%{transform:scale(0);opacity:.2}35%{opacity:1}100%{transform:scale(1);opacity:1}}
@keyframes sp-drift{from{transform:scale(1)}to{transform:scale(1.035)}}
@media (prefers-reduced-motion:reduce){#splash .sp-m{animation:none;stroke-dashoffset:0}#splash .sp-sun{animation:none;transform:none}#splash .sp-glyph,#splash .sp-tile{animation:none}}
#splash.calm .sp-m{animation:none;stroke-dashoffset:0}#splash.calm .sp-sun{animation:none;transform:none}#splash.calm .sp-glyph,#splash.calm .sp-tile{animation:none}`;
const k0 = 1; // the splash tile is a 512 box with the same padding as the icon
const pad = 0.13, inner = 512 * (1 - pad * 2), kk = inner / 109, ox = 512 * pad, oy = 512 * pad + 512 * 0.012;
const splash = `<div id="splash" aria-hidden="true"><div class="sp-tile"><svg viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg"><defs>${defs("s")}<clipPath id="s-clip"><rect width="512" height="512" rx="112"/></clipPath>
${centre.map((d, i) => `<mask id="s-m${i}" maskUnits="userSpaceOnUse" x="-20" y="-20" width="150" height="150"><path class="sp-m" pathLength="${Math.round(lengths[i])}" style="--len:${Math.round(lengths[i])};--ms:${timing[i].ms}ms;--d:${timing[i].delay}ms" d="${d}"/></mask>`).join("")}</defs>
<g clip-path="url(#s-clip)"><rect width="512" height="512" fill="${PAPER}"/><rect width="512" height="512" filter="url(#s-paper)" opacity=".5"/><rect width="512" height="512" fill="url(#s-vig)"/>
<circle class="sp-sun" cx="${(512 * 0.665).toFixed(1)}" cy="${(512 * 0.335).toFixed(1)}" r="${(512 * 0.205).toFixed(1)}" fill="${SUN}" filter="url(#s-sunf)"/>
<g class="sp-glyph"><g transform="translate(${ox.toFixed(1)} ${oy.toFixed(1)}) scale(${kk.toFixed(4)})" fill="${INK}" filter="url(#s-ink)">${outlines.map((d, i) => `<path mask="url(#s-m${i})" d="${d}"/>`).join("")}</g></g></g></svg></div></div>`;
void k0;
let html = fs.readFileSync("index.html", "utf8");
const A = "<!-- splash:css -->", B = "<!-- /splash:css -->", C = "<!-- splash:html -->", D = "<!-- /splash:html -->";
const swap = (s, a, z, body) => { const i = s.indexOf(a), j = s.indexOf(z); if (i < 0 || j < 0) throw new Error("markers missing in index.html"); return s.slice(0, i + a.length) + "\n" + body + "\n" + s.slice(j); };
html = swap(html, A, B, `<style>${css}\n</style>`);
html = swap(html, C, D, splash);
fs.writeFileSync("index.html", html);
await b.close();
console.log("icons, ink glyph and splash written; strokes finish at", strokesEnd, "ms");
